// Hàm khởi tạo trò chơi - tạo grid với bom ngẫu nhiên
export const initializeGame = () => {
  // Tạo mảng 25 ô
  const cells = Array.from({ length: 25 }, (_, index) => ({
    id: index + 1,
    isBomb: false,
    isRevealed: false,
    questionId: null
  }));

  // Chọn 6 vị trí ngẫu nhiên cho bom
  const bombPositions = new Set();
  while (bombPositions.size < 6) {
    bombPositions.add(Math.floor(Math.random() * 25));
  }

  // Đánh dấu các ô bom
  bombPositions.forEach(pos => {
    cells[pos].isBomb = true;
  });

  // Gán câu hỏi cho các ô không phải bom
  let questionIndex = 0;
  cells.forEach((cell) => {
    if (!cell.isBomb && questionIndex < minigameQuestions.length) {
      cell.questionId = minigameQuestions[questionIndex].id;
      questionIndex++;
    }
  });

  return cells;
};

// Hàm lấy câu hỏi theo ID
export const getQuestionById = (questionId) => {
  return minigameQuestions.find(q => q.id === questionId) || null;
};
